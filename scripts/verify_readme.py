class ClaimDrift(Exception):
    """Raised when a README claim does not match its regenerated value."""


# ---------------------------------------------------------------------------
# Unregistered-numeric scanner
# ---------------------------------------------------------------------------

# Matches a CLAIM block (open tag + content + close tag), used to strip them
# before scanning for bare numbers.
_CLAIM_BLOCK_STRIP_RE = re.compile(
    r"<!--\s*CLAIM:\w+\s*-->.*?<!--\s*/CLAIM:\w+\s*-->",
    re.DOTALL,
)

# Float literal: e.g. 0.837, 23.9, 1.329  (≥ 2 significant decimal digits)
# This deliberately excludes single-decimal values like "1.0" or "0.5" which
# appear legitimately in configuration prose.
_FLOAT_RE = re.compile(
    r"(?<![/\w])(\d+\.\d{2,})(?![\d/])"
)

# Scientific notation — both ASCII (1e-4, 5.3e-06) and Unicode superscript
# forms (4.7×10⁻⁶, 5.3×10⁻⁶).
_SCI_NOTATION_RE = re.compile(
    r"(?:"
    # ASCII: optional coefficient × base^exp, e.g. 5.3e-06, 1e-4, 2.5e+3
    r"[0-9]+(?:\.[0-9]+)?[eE][+\-]?[0-9]+"
    r"|"
    # Unicode: N×10^exp with Unicode superscript digits / minus
    r"[0-9]+(?:\.[0-9]+)?\s*[×x]\s*10[⁰¹²³⁴⁵⁶⁷⁸⁹⁺⁻−\-]+[⁰¹²³⁴⁵⁶⁷⁸⁹]+"
    r")"
)

# Lines that are code fences, HTML comments, or contain only Markdown syntax
# are excluded from the scan (their content is structural, not prose claims).
_SKIP_LINE_RE = re.compile(
    r"^\s*(?:```|<!--|\|[-| ]+\||\s*#)"
)


def scan_readme_for_unregistered_numerics(
    readme_text: str,
    readme_path: Path,
) -> list[str]:
    """
    Scan README text *outside* CLAIM blocks for float and scientific-notation
    tokens that could be unregistered scientific claims.

    Returns a list of error strings (file:line: token).  Empty list = clean.
    """
    # Strip CLAIM block content (open tag through close tag) so we do not
    # flag numbers that are already registered.
    stripped = _CLAIM_BLOCK_STRIP_RE.sub("", readme_text)

    errors: list[str] = []
    for lineno, raw_line in enumerate(stripped.splitlines(), start=1):
        # Skip structural Markdown lines: code fences, table separators, etc.
        if _SKIP_LINE_RE.match(raw_line):
            continue

        # Also skip bare HTML comment lines (e.g. <!-- CLAIM:foo --> after strip)
        line = raw_line.strip()
        if line.startswith("<!--") or line.startswith("//"):
            continue

        # Collect all candidate tokens on this line
        candidates: list[str] = []
        for m in _SCI_NOTATION_RE.finditer(raw_line):
            candidates.append(m.group())
        # Float regex only applied to portions not already matched by sci-notation
        sci_spans = [m.span() for m in _SCI_NOTATION_RE.finditer(raw_line)]

        def _in_sci_span(start: int) -> bool:
            return any(s <= start < e for s, e in sci_spans)

        for m in _FLOAT_RE.finditer(raw_line):
            if not _in_sci_span(m.start()):
                candidates.append(m.group())

        for token in candidates:
            if token in _NUMERIC_ALLOWLIST:
                continue
            errors.append(
                f"{readme_path}:{lineno}: unregistered numeric token '{token}'"
            )

    return errors


def verify_all_claims(
    readme_path: Path,
    strict: bool = False,
) -> tuple[list[str], list[str], list[str]]:
    """
    Verify all claims in the README against regenerated values.

    Returns three lists:
      errors   — claims that have drifted (published ≠ regenerated)
      warnings — claims in registry with no block in README, or vice versa
      oks      — claims that match
    """
    readme_text = readme_path.read_text(encoding="utf-8")
    readme_claims = parse_readme_claims(readme_text)

    errors: list[str] = []
    warnings: list[str] = []
    oks: list[str] = []

    # Check every registered claim exists in README and matches
    for claim_name, regen_fn in CLAIM_REGISTRY.items():
        if claim_name not in readme_claims:
            msg = (
                f"MISSING BLOCK  [{claim_name}]  "
                f"No <!-- CLAIM:{claim_name} --> block found in {readme_path.name}. "
                f"Add the block or remove the registry entry."
            )
            if strict:
                errors.append(msg)
            else:
                warnings.append(msg)
            continue

        published = readme_claims[claim_name]
        try:
            regenerated = regen_fn()
        except Exception as exc:
            errors.append(
                f"REGEN ERROR    [{claim_name}]  "
                f"Failed to regenerate: {exc}"
            )
            continue

        if published != regenerated:
            errors.append(
                f"DRIFT          [{claim_name}]\n"
                f"  Published  : {published!r}\n"
                f"  Regenerated: {regenerated!r}"
            )
        else:
            oks.append(f"OK             [{claim_name}]  {published!r}")

    # Check every README claim has a registry entry
    for claim_name in readme_claims:
        if claim_name not in CLAIM_REGISTRY:
            msg = (
                f"UNREGISTERED   [{claim_name}]  "
                f"README has <!-- CLAIM:{claim_name} --> but no registry entry in "
                f"scripts/verify_readme.py.  "
                f"Add a regeneration function or remove the block."
            )
            if strict:
                errors.append(msg)
            else:
                warnings.append(msg)

    return errors, warnings, oks


def parse_args(argv: list[str] | None = None) -> argparse.Namespace:
    p = argparse.ArgumentParser(
        description=(
            "Verify README.md numeric claims against committed artifacts. "
            "Exits non-zero on any drift."
        )
    )
    p.add_argument(
        "--readme",
        type=Path,
        default=REPO_ROOT / "README.md",
        help="Path to README.md (default: repo root README.md)",
    )
    p.add_argument(
        "--strict",
        action="store_true",
        help="Treat unregistered/missing blocks as errors (default: warnings only)",
    )
    p.add_argument(
        "--list-claims",
        action="store_true",
        help="Print registered claim names and their sources, then exit 0",
    )
    return p.parse_args(argv)


def main(argv: list[str] | None = None) -> int:
    args = parse_args(argv)

    if args.list_claims:
        print("Registered README claims:")
        for name, fn in CLAIM_REGISTRY.items():
            doc = (fn.__doc__ or "").strip().split("\n")[0]
            print(f"  {name:30s}  {doc}")
        return 0

    if not args.readme.exists():
        print(f"ERROR: README not found: {args.readme}", file=sys.stderr)
        return 2

    readme_text = args.readme.read_text(encoding="utf-8")

    # Pass 1: verify CLAIM blocks match regenerated values
    errors, warnings, oks = verify_all_claims(args.readme, strict=args.strict)

    for line in oks:
        print(line)
    for line in warnings:
        print(f"WARNING: {line}", file=sys.stderr)
    for line in errors:
        print(f"ERROR: {line}", file=sys.stderr)

    if errors:
        print(
            f"\n{len(errors)} claim(s) failed verification.  "
            "Update README.md or fix the source of truth, then re-run.",
            file=sys.stderr,
        )
        return 1

    # Pass 2: scan for unregistered numerics outside CLAIM blocks
    unregistered = scan_readme_for_unregistered_numerics(readme_text, args.readme)
    for line in unregistered:
        print(f"UNREGISTERED NUMERIC: {line}", file=sys.stderr)
    if unregistered:
        print(
            f"\n{len(unregistered)} unregistered numeric token(s) found outside "
            "CLAIM blocks.  Wrap each value in a <!-- CLAIM:name --> block or "
            "add it to _NUMERIC_ALLOWLIST in scripts/verify_readme.py.",
            file=sys.stderr,
        )
        return 2

    if warnings:
        print(
            f"\n{len(warnings)} warning(s).  "
            "Pass --strict to treat these as errors.",
            file=sys.stderr,
        )

    print(f"\n{len(oks)} claim(s) verified OK.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
