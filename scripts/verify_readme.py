#!/usr/bin/env python3
"""
scripts/verify_readme.py
==========================
Regenerate every numeric claim in README.md from committed inputs and diff
against the published values.  Exits non-zero on any drift.

Purpose
-------
README.md contains ``<!-- CLAIM:name -->`` / ``<!-- /CLAIM:name -->`` blocks.
Each block wraps exactly one human-readable line that contains a numeric or
versioned claim.  This script:

  1. Reads each claim block from README.md.
  2. Regenerates the expected value from the committed artifact or source file.
  3. Compares the regenerated value to the published text.
  4. Reports all drifts and exits 1 if any are found.

This enforces AGENTS.md Rule 5:
  "No claim appears in the README that is not regenerated by the
   reproducibility script."

Claim registry
--------------
Each entry below names:
  - the CLAIM id (matches the HTML comment tag in README.md)
  - the source of truth (a committed file or Python import)
  - the regeneration function

Adding a new claim
------------------
1. Add a ``<!-- CLAIM:name -->`` block to README.md.
2. Add an entry to CLAIM_REGISTRY below.
3. Run this script locally; it will fail until README.md matches.

CI wiring
---------
Add to your CI workflow (GitHub Actions, etc.):

  - name: Verify README claims
    run: python scripts/verify_readme.py

The step exits non-zero on any drift, blocking merge.

Usage
-----
    python scripts/verify_readme.py [--readme README.md] [--strict]

  --readme PATH   Path to README.md (default: README.md in repo root)
  --strict        Treat warnings as errors (default: only drift is an error)

Exit codes
----------
  0   All claims match their regenerated values.
  1   One or more claims have drifted.
  2   A claim listed in CLAIM_REGISTRY has no corresponding block in README.md,
      or a block in README.md has no registered regeneration function.
"""

from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path
from typing import Callable

REPO_ROOT = Path(__file__).parent.parent

# ---------------------------------------------------------------------------
# Claim regeneration functions
# Each function returns the exact string that the README block should contain.
# The string must match the line (stripped) inside the CLAIM block.
# ---------------------------------------------------------------------------

def _regen_falsifier_version() -> str:
    """Read __version__ from falsifier/__init__.py."""
    init_path = REPO_ROOT / "falsifier" / "__init__.py"
    text = init_path.read_text(encoding="utf-8")
    m = re.search(r'__version__\s*=\s*["\']([^"\']+)["\']', text)
    if not m:
        raise ValueError(f"Could not find __version__ in {init_path}")
    version = m.group(1)
    return f"Pipeline version: `{version}`"


def _regen_n_golden_targets() -> str:
    """Count entries in data/golden/MANIFEST.json."""
    manifest_path = REPO_ROOT / "data" / "golden" / "MANIFEST.json"
    if not manifest_path.exists():
        raise FileNotFoundError(f"Missing: {manifest_path}")
    with open(manifest_path, encoding="utf-8") as f:
        data = json.load(f)
    n = len(data.get("golden_set", []))
    return f"Committed golden targets: {n}"


def _regen_n_vetting_tests() -> str:
    """Count VettingTestName values in vet.py."""
    vet_path = REPO_ROOT / "falsifier" / "pipeline" / "contracts" / "vet.py"
    text = vet_path.read_text(encoding="utf-8")
    # VETTING_TEST_ORDER tuple is the canonical source
    m = re.search(
        r'VETTING_TEST_ORDER\s*:\s*tuple\[str,\s*\.\.\.\]\s*=\s*\((.*?)\)',
        text,
        re.DOTALL,
    )
    if not m:
        raise ValueError("Could not find VETTING_TEST_ORDER in vet.py")
    entries = [e.strip().strip('"').strip("'") for e in m.group(1).split(",") if e.strip()]
    n = len(entries)
    return f"Vetting tests: {n}"


def _regen_period_tolerance_days() -> str:
    """Read PERIOD_TOLERANCE_DAYS from test_kepler10_recovery.py."""
    test_path = REPO_ROOT / "tests" / "test_kepler10_recovery.py"
    text = test_path.read_text(encoding="utf-8")
    m = re.search(r'PERIOD_TOLERANCE_DAYS\s*=\s*([0-9eE+\-\.]+)', text)
    if not m:
        raise ValueError("Could not find PERIOD_TOLERANCE_DAYS in test_kepler10_recovery.py")
    tol = float(m.group(1))
    seconds = tol * 86400.0
    return f"Period recovery tolerance: {tol:.0e} days (~{seconds:.1f} s)"


def _regen_kepler10b_period_days() -> str:
    """Read KEPLER10B_PERIOD_DAYS from test_kepler10_recovery.py."""
    test_path = REPO_ROOT / "tests" / "test_kepler10_recovery.py"
    text = test_path.read_text(encoding="utf-8")
    m = re.search(r'KEPLER10B_PERIOD_DAYS\s*=\s*([0-9.]+)', text)
    if not m:
        raise ValueError("Could not find KEPLER10B_PERIOD_DAYS in test_kepler10_recovery.py")
    period = float(m.group(1))
    return f"Kepler-10b published period (Batalha et al. 2011): {period:.8f} days"


def _regen_eb_depth_ratio() -> str:
    """Read depth_ratio_primary_over_secondary from data/golden/MANIFEST.json."""
    manifest_path = REPO_ROOT / "data" / "golden" / "MANIFEST.json"
    if not manifest_path.exists():
        raise FileNotFoundError(f"Missing: {manifest_path}")
    with open(manifest_path, encoding="utf-8") as f:
        data = json.load(f)
    # Find the KIC 6965293 entry
    for entry in data.get("golden_set", []):
        if "6965293" in entry.get("kic_id", ""):
            catalog = entry.get("eb_catalog", {})
            ratio = catalog.get("depth_ratio_primary_over_secondary")
            if ratio is None:
                raise ValueError("depth_ratio_primary_over_secondary missing from MANIFEST.json")
            return f"KIC 6965293 EB depth ratio (Prša et al. 2011): {ratio:.2f} primary/secondary"
    raise ValueError("KIC 6965293 entry not found in MANIFEST.json golden_set")


# ---------------------------------------------------------------------------
# Claim registry
# Maps CLAIM id → regeneration function
# ---------------------------------------------------------------------------

CLAIM_REGISTRY: dict[str, Callable[[], str]] = {
    "falsifier_version": _regen_falsifier_version,
    "n_golden_targets": _regen_n_golden_targets,
    "n_vetting_tests": _regen_n_vetting_tests,
    "period_tolerance_days": _regen_period_tolerance_days,
    "kepler10b_period_days": _regen_kepler10b_period_days,
    "eb_depth_ratio": _regen_eb_depth_ratio,
}


# ---------------------------------------------------------------------------
# README parser
# ---------------------------------------------------------------------------

# Matches:  <!-- CLAIM:name -->
# followed by exactly one content line (may have Markdown formatting)
# followed by:  <!-- /CLAIM:name -->
_CLAIM_BLOCK_RE = re.compile(
    r"<!--\s*CLAIM:(?P<name>\w+)\s*-->\n"
    r"(?P<content>[^\n]*)\n"
    r"<!--\s*/CLAIM:(?P=name)\s*-->",
    re.MULTILINE,
)


def parse_readme_claims(readme_text: str) -> dict[str, str]:
    """
    Extract all CLAIM blocks from README text.

    Returns a dict mapping claim name → stripped content line.
    """
    claims: dict[str, str] = {}
    for m in _CLAIM_BLOCK_RE.finditer(readme_text):
        name = m.group("name")
        content = m.group("content").strip()
        if name in claims:
            raise ValueError(
                f"Duplicate CLAIM block '{name}' in README.md.  "
                "Each claim name must appear exactly once."
            )
        claims[name] = content
    return claims


# ---------------------------------------------------------------------------
# Main verification logic
# ---------------------------------------------------------------------------

class ClaimDrift(Exception):
    """Raised when a README claim does not match its regenerated value."""


def verify_all_claims(
    readme_path: Path,
    strict: bool = False,
) -> tuple[list[str], list[str], list[str]]:
    """
    Verify all claims in the README against regenerated values.

    Returns three lists:
      errors   — claims that have drifted (published ≠ regenerated)
      warnings — claims in registry with no block in README, or vice versa
      oks      — claims that match
    """
    readme_text = readme_path.read_text(encoding="utf-8")
    readme_claims = parse_readme_claims(readme_text)

    errors: list[str] = []
    warnings: list[str] = []
    oks: list[str] = []

    # Check every registered claim exists in README and matches
    for claim_name, regen_fn in CLAIM_REGISTRY.items():
        if claim_name not in readme_claims:
            msg = (
                f"MISSING BLOCK  [{claim_name}]  "
                f"No <!-- CLAIM:{claim_name} --> block found in {readme_path.name}. "
                f"Add the block or remove the registry entry."
            )
            if strict:
                errors.append(msg)
            else:
                warnings.append(msg)
            continue

        published = readme_claims[claim_name]
        try:
            regenerated = regen_fn()
        except Exception as exc:
            errors.append(
                f"REGEN ERROR    [{claim_name}]  "
                f"Failed to regenerate: {exc}"
            )
            continue

        if published != regenerated:
            errors.append(
                f"DRIFT          [{claim_name}]\n"
                f"  Published  : {published!r}\n"
                f"  Regenerated: {regenerated!r}"
            )
        else:
            oks.append(f"OK             [{claim_name}]  {published!r}")

    # Check every README claim has a registry entry
    for claim_name in readme_claims:
        if claim_name not in CLAIM_REGISTRY:
            msg = (
                f"UNREGISTERED   [{claim_name}]  "
                f"README has <!-- CLAIM:{claim_name} --> but no registry entry in "
                f"scripts/verify_readme.py.  "
                f"Add a regeneration function or remove the block."
            )
            if strict:
                errors.append(msg)
            else:
                warnings.append(msg)

    return errors, warnings, oks


def parse_args(argv: list[str] | None = None) -> argparse.Namespace:
    p = argparse.ArgumentParser(
        description=(
            "Verify README.md numeric claims against committed artifacts. "
            "Exits non-zero on any drift."
        )
    )
    p.add_argument(
        "--readme",
        type=Path,
        default=REPO_ROOT / "README.md",
        help="Path to README.md (default: repo root README.md)",
    )
    p.add_argument(
        "--strict",
        action="store_true",
        help="Treat unregistered/missing blocks as errors (default: warnings only)",
    )
    p.add_argument(
        "--list-claims",
        action="store_true",
        help="Print registered claim names and their sources, then exit 0",
    )
    return p.parse_args(argv)


def main(argv: list[str] | None = None) -> int:
    args = parse_args(argv)

    if args.list_claims:
        print("Registered README claims:")
        for name, fn in CLAIM_REGISTRY.items():
            doc = (fn.__doc__ or "").strip().split("\n")[0]
            print(f"  {name:30s}  {doc}")
        return 0

    if not args.readme.exists():
        print(f"ERROR: README not found: {args.readme}", file=sys.stderr)
        return 2

    errors, warnings, oks = verify_all_claims(args.readme, strict=args.strict)

    for line in oks:
        print(line)
    for line in warnings:
        print(f"WARNING: {line}", file=sys.stderr)
    for line in errors:
        print(f"ERROR: {line}", file=sys.stderr)

    if errors:
        print(
            f"\n{len(errors)} claim(s) failed verification.  "
            "Update README.md or fix the source of truth, then re-run.",
            file=sys.stderr,
        )
        return 1

    if warnings:
        print(
            f"\n{len(warnings)} warning(s).  "
            "Pass --strict to treat these as errors.",
            file=sys.stderr,
        )

    print(f"\n{len(oks)} claim(s) verified OK.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
